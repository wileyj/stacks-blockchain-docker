package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

// Marker is the first line of every rendered file. A Config.toml/Signer.toml without it was written
// by hand (or by manage.sh before the renderer existed) and is moved aside once, not overwritten.
const Marker = "# Generated by the config job"

// Settings are the deployment values taken from .env (via the compose `environment:` of the job).
type Settings struct {
	Network              string
	Profiles             map[string]bool
	BTCHost              string
	BTCRPCUser           string
	BTCRPCPass           string
	BTCRPCPort           string
	BTCP2PPort           string
	AuthToken            string
	NodeMetricsPort      string
	SignerPort           string
	SignerMetricsPort    string
	APIEventEndpoint     string
	APIObserverTimeoutMS string
	CoreRPCHost          string
	CoreRPCPort          string
	SignerKey            string
	// ContainerMetrics: cAdvisor runs with the monitoring profile (MONITORING_CONTAINER_METRICS=1)
	ContainerMetrics bool
}

// SettingsFromEnv reads and validates the settings. Empty values keep the template's value.
func SettingsFromEnv(getenv func(string) string) (Settings, error) {
	s := Settings{Network: strings.TrimSpace(getenv("NETWORK")), Profiles: map[string]bool{}}
	switch s.Network {
	case "mainnet", "testnet":
	case "":
		return s, fmt.Errorf("NETWORK is not set: copy sample.env to .env (cp sample.env .env) and run again")
	default:
		return s, fmt.Errorf("NETWORK=%q is not supported (mainnet or testnet)", s.Network)
	}
	for _, p := range strings.Split(getenv("COMPOSE_PROFILES"), ",") {
		if p = strings.ToLower(strings.TrimSpace(p)); p != "" {
			s.Profiles[p] = true
		}
	}
	if s.Profiles["*"] {
		for _, p := range []string{"node", "api", "signer", "proxy", "monitoring"} {
			s.Profiles[p] = true
		}
	}

	// Testnet has its own BTC peer and signer key variables (contract §A.15)
	btc, key := "BTC_", "SIGNER_PRIVATE_KEY"
	if s.Network == "testnet" {
		btc, key = "TBTC_", "TESTNET_SIGNER_PRIVATE_KEY"
	}
	s.BTCHost = getenv(btc + "HOST")
	s.BTCRPCUser = getenv(btc + "RPC_USER")
	s.BTCRPCPass = getenv(btc + "RPC_PASS")
	s.BTCRPCPort = getenv(btc + "RPC_PORT")
	s.BTCP2PPort = getenv(btc + "P2P_PORT")
	s.SignerKey = strings.TrimSpace(getenv(key))
	s.AuthToken = getenv("AUTH_TOKEN")
	s.NodeMetricsPort = getenv("NODE_METRICS_PORT")
	s.SignerPort = orDefault(getenv("STACKS_SIGNER_PORT"), "30000")
	s.SignerMetricsPort = getenv("SIGNER_METRICS_PORT")
	s.CoreRPCHost = orDefault(getenv("STACKS_CORE_RPC_HOST"), "stacks-blockchain")
	s.CoreRPCPort = orDefault(getenv("STACKS_CORE_RPC_PORT"), "20443")
	s.APIEventEndpoint = orDefault(getenv("API_EVENT_ENDPOINT"),
		"stacks-blockchain-api:"+orDefault(getenv("STACKS_CORE_EVENT_PORT"), "3700"))
	s.APIObserverTimeoutMS = orDefault(getenv("API_OBSERVER_TIMEOUT_MS"), "60000")
	switch v := orDefault(getenv("MONITORING_CONTAINER_METRICS"), "1"); v {
	case "1":
		s.ContainerMetrics = true
	case "0":
	default:
		return s, fmt.Errorf("MONITORING_CONTAINER_METRICS must be 0 or 1, got %q", v)
	}

	for name, v := range map[string]string{
		btc + "RPC_PORT": s.BTCRPCPort, btc + "P2P_PORT": s.BTCP2PPort, "NODE_METRICS_PORT": s.NodeMetricsPort,
		"STACKS_SIGNER_PORT": s.SignerPort, "SIGNER_METRICS_PORT": s.SignerMetricsPort,
		"STACKS_CORE_RPC_PORT": s.CoreRPCPort, "API_OBSERVER_TIMEOUT_MS": s.APIObserverTimeoutMS,
	} {
		if v != "" {
			if _, err := strconv.ParseUint(v, 10, 32); err != nil {
				return s, fmt.Errorf("%s must be a number, got %q", name, v)
			}
		}
	}
	return s, nil
}

// Observers returns the [[events_observer]] entries for the enabled profiles, so the node never
// blocks on an observer that isn't running (D46, #153).
func (s Settings) Observers() []any {
	var obs []any
	if s.Profiles["api"] {
		ms, _ := strconv.ParseInt(s.APIObserverTimeoutMS, 10, 64)
		obs = append(obs, map[string]any{
			"endpoint":    s.APIEventEndpoint,
			"events_keys": []any{"*"},
			"timeout_ms":  ms,
		})
	}
	if s.Profiles["signer"] {
		obs = append(obs, map[string]any{
			"endpoint":    "stacks-signer:" + s.SignerPort,
			"events_keys": []any{"stackerdb", "block_proposal", "burn_blocks"},
		})
	}
	return obs
}

// RenderNode renders Config.toml from the network template, the settings and the user's overrides.
func RenderNode(tmpl, overrides []byte, s Settings, source string) ([]byte, error) {
	m, err := parse(tmpl, "template")
	if err != nil {
		return nil, err
	}
	node, burn, conn := table(m, "node"), table(m, "burnchain"), table(m, "connection_options")

	setString(burn, "peer_host", s.BTCHost)
	if err := setInt(burn, "rpc_port", s.BTCRPCPort); err != nil {
		return nil, err
	}
	if err := setInt(burn, "peer_port", s.BTCP2PPort); err != nil {
		return nil, err
	}
	// A follower needs no bitcoind RPC credentials (refactor/15 P1): drop the keys when unset
	setOrDelete(burn, "username", s.BTCRPCUser)
	setOrDelete(burn, "password", s.BTCRPCPass)
	setString(conn, "auth_token", s.AuthToken)
	if s.NodeMetricsPort != "" {
		node["prometheus_bind"] = "0.0.0.0:" + s.NodeMetricsPort
	}
	node["stacker"] = s.Profiles["signer"]
	delete(m, "events_observer")
	if obs := s.Observers(); len(obs) > 0 {
		m["events_observer"] = obs
	}
	return finish(m, overrides, source)
}

// RenderSigner renders Signer.toml. The signer needs its private key (contract §A.10).
func RenderSigner(tmpl, overrides []byte, s Settings, source string) ([]byte, error) {
	if s.SignerKey == "" {
		key := "SIGNER_PRIVATE_KEY"
		if s.Network == "testnet" {
			key = "TESTNET_SIGNER_PRIVATE_KEY"
		}
		return nil, fmt.Errorf("the signer profile is enabled but %s is empty in .env", key)
	}
	m, err := parse(tmpl, "template")
	if err != nil {
		return nil, err
	}
	m["node_host"] = s.CoreRPCHost + ":" + s.CoreRPCPort
	m["endpoint"] = "0.0.0.0:" + s.SignerPort
	if s.SignerMetricsPort != "" {
		m["metrics_endpoint"] = "0.0.0.0:" + s.SignerMetricsPort
	}
	m["auth_password"] = s.AuthToken
	m["stacks_private_key"] = s.SignerKey
	return finish(m, overrides, source)
}

func finish(m map[string]any, overrides []byte, source string) ([]byte, error) {
	if len(overrides) > 0 {
		o, err := parse(overrides, "overrides")
		if err != nil {
			return nil, err
		}
		merge(m, o)
	}
	out, err := toml.Marshal(m)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("%s from %s. Do not edit: it is rewritten on every `docker compose up`.\n"+
		"# Put your changes in the matching *.overrides.toml next to this file.\n\n", Marker, source)
	return append([]byte(header), out...), nil
}

// merge applies overrides onto base: tables merge recursively, [[events_observer]] entries are
// appended (extra observers), and every other value replaces the base value.
func merge(base, over map[string]any) {
	keys := make([]string, 0, len(over))
	for k := range over {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		v := over[k]
		if k == "events_observer" {
			if extra, ok := v.([]any); ok {
				existing, _ := base[k].([]any)
				base[k] = append(existing, extra...)
				continue
			}
		}
		if ov, ok := v.(map[string]any); ok {
			if bv, ok := base[k].(map[string]any); ok {
				merge(bv, ov)
				continue
			}
		}
		base[k] = v
	}
}

func parse(b []byte, what string) (map[string]any, error) {
	m := map[string]any{}
	if err := toml.Unmarshal(b, &m); err != nil {
		return nil, fmt.Errorf("invalid TOML in %s: %w", what, err)
	}
	return m, nil
}

func table(m map[string]any, name string) map[string]any {
	if t, ok := m[name].(map[string]any); ok {
		return t
	}
	t := map[string]any{}
	m[name] = t
	return t
}

func setString(t map[string]any, key, v string) {
	if v != "" {
		t[key] = v
	}
}

func setOrDelete(t map[string]any, key, v string) {
	if v == "" {
		delete(t, key)
		return
	}
	t[key] = v
}

func setInt(t map[string]any, key, v string) error {
	if v == "" {
		return nil
	}
	n, err := strconv.ParseInt(v, 10, 64)
	if err != nil {
		return fmt.Errorf("%s must be a number, got %q", key, v)
	}
	t[key] = n
	return nil
}

func orDefault(v, def string) string {
	if strings.TrimSpace(v) == "" {
		return def
	}
	return v
}
