package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/pelletier/go-toml/v2"
)

// TemplateMarker starts every generated conf/<network>/Config.toml.sample.
const TemplateMarker = "# Generated by `config template`"

// deploymentKeys are owned by this repo (Config.deployment.toml) or rendered from .env, so they are
// dropped from the upstream sample: only the network definition (bootstrap node, mode, pox_5_*,
// [[ustx_balance]], [[burnchain.epochs]], ...) is taken from upstream (refactor/11 Q27).
var deploymentKeys = map[string][]string{
	"":          {"events_observer", "connection_options"},
	"node":      {"working_dir", "rpc_bind", "p2p_bind", "prometheus_bind", "miner", "stacker", "seed", "local_peer_seed"},
	"burnchain": {"peer_host", "rpc_port", "peer_port", "username", "password"},
}

// Template builds a network template: the upstream sample without its deployment keys, with the
// repo's deployment layer merged on top.
func Template(upstream, deployment []byte, source string) ([]byte, error) {
	m, err := parse(upstream, "upstream sample")
	if err != nil {
		return nil, err
	}
	for name, keys := range deploymentKeys {
		t := m
		if name != "" {
			var ok bool
			if t, ok = m[name].(map[string]any); !ok {
				continue
			}
		}
		for _, k := range keys {
			delete(t, k)
		}
	}
	d, err := parse(deployment, "deployment layer")
	if err != nil {
		return nil, err
	}
	merge(m, d)
	out, err := toml.Marshal(m)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf("%s from %s.\n"+
		"# Do not edit: regenerate with tools/sync-upstream-conf.sh. Repo-specific defaults belong in\n"+
		"# Config.deployment.toml, user settings in Config.overrides.toml.\n\n", TemplateMarker, source)
	return append([]byte(header), out...), nil
}

// runTemplate is the `config template` subcommand used by tools/sync-upstream-conf.sh.
func runTemplate(args []string) error {
	fs := flag.NewFlagSet("template", flag.ContinueOnError)
	upstreamPath := fs.String("upstream", "", "upstream sample (conf/upstream/<network>-follower-conf.toml)")
	deploymentPath := fs.String("deployment", "", "repo deployment layer (conf/<network>/Config.deployment.toml)")
	source := fs.String("source", "", "provenance for the header, e.g. stacks-core@<sha> sample/conf/<file>")
	outPath := fs.String("out", "", "output template (conf/<network>/Config.toml.sample)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *upstreamPath == "" || *deploymentPath == "" || *source == "" || *outPath == "" {
		return fmt.Errorf("template: -upstream, -deployment, -source and -out are required")
	}
	upstream, err := os.ReadFile(*upstreamPath)
	if err != nil {
		return err
	}
	deployment, err := os.ReadFile(*deploymentPath)
	if err != nil {
		return err
	}
	out, err := Template(upstream, deployment, *source)
	if err != nil {
		return fmt.Errorf("template %s: %w", *outPath, err)
	}
	return writeAtomic(*outPath, out, 0o644)
}
